	int drawText(Framebuffer &fb, int x, int y, const std::string &text, Color color, int scale)
	{
		for (char c : text)
		{
			const std::uint8_t *rows = findGlyph(c);

			if (rows)
			{
				for (int r = 0; r < GLYPH_H; ++r)
				{
					for (int col = 0; col < GLYPH_W; ++col)
					{
						if (rows[r] & (0x10 >> col))
						{
							fb.fillRect(x + col * scale, y + r * scale, scale, scale, color);
						}
					}
				}
			}
			else
			{
				// Character not in the font: draw a hollow box so it's easy to spot
				fb.fillRect(x, y, GLYPH_W * scale, scale, color);
				fb.fillRect(x, y + 6 * scale, GLYPH_W * scale, scale, color);
				fb.fillRect(x, y, scale, 7 * scale, color);
				fb.fillRect(x + (GLYPH_W - 1) * scale, y, scale, 7 * scale, color);
			}

			x += GLYPH_ADVANCE * scale;
		}
		return x;
	}

	int textWidth(const std::string &text, int scale)
	{
		if (text.empty())
			return 0;
		return (static_cast<int>(text.size()) * GLYPH_ADVANCE - 1) * scale;
	}

